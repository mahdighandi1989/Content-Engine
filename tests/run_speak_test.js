  const dropped = V('ما باید همین جا بایستیم و نگاه کنیم.');
  ok('۳الف.۴ نیم‌فاصلهٔ برداشته‌شده هم برمی‌گردد',
     bare(speakGraft_(plain, dropped)).indexOf('همین' + Z + 'جا') !== -1,
     JSON.stringify(speakGraft_(plain, dropped)));
