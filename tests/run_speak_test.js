  const plain = 'ما باید همین‌جا بایستیم و نگاه کنیم.';
  // مقایسه‌ها روی متنِ بی‌اعراب انجام می‌شود: V() بین هر دو حرف فتحه
  // می‌گذارد، پس جست‌وجوی رشتهٔ خام همیشه «پیدا نشد» می‌دهد و سنجه
  // بی‌آنکه بفهمیم سبز می‌مانَد — همان دامِ «آزمونی که شکلِ راحت را می‌سنجد».
  const bare = t => stripTashkil_(t);
