#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
fa2latin_test.py — جدولِ واژه‌های شناخته‌شده.

══ چرا جدول، نه چشم ══
یک برگردانِ آوایی صد قاعدهٔ ریز دارد و هر قاعدهٔ تازه می‌تواند قاعدهٔ
پیشین را بشکند — «و» را که درست کنی «ی» خراب می‌شود. تنها چیزی که جلوی
این را می‌گیرد فهرستی از واژه‌هایی است که جوابشان را از پیش می‌دانیم.

واژه‌ها عمداً از همان متنی برداشته شده‌اند که آزمایشگاهِ صدا می‌فرستد، به
اضافهٔ استثناهای مشهورِ خطِ فارسی (خواب، نو، دود).
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fa2latin as F

# (متنِ اعراب‌دار، فینگلیشِ درست، چرا این مورد هست)
CASES = [
    ("دَر",            "dar",        "ساده‌ترین حالت"),
    ("دود",            "dud",        "واو پس از همخوانِ برهنه = مصوتِ او"),
    ("دَوَم",           "davam",      "واو پیش از اعراب = همخوان"),
    ("نَو",            "now",        "واو در پایان پس از فتحه = دوگانه‌واکه"),
    ("خواب",           "khâb",       "استثنای «خو»: واو نوشته می‌شود، خوانده نه"),
    ("خورد",           "khord",      "استثنای «خو»: واو مصوتِ کوتاه است"),
    ("می‌تَوانَد",       "mitavânad",  "واو پیش از الف = همخوان"),
    ("اُستوار",         "ostovâr",    "«وا» پس از همخوانِ برهنه = o + v"),
    ("دیر",            "dir",        "یای پس از همخوانِ برهنه = مصوتِ ای"),
    ("پِیوَند",         "peyvand",    "یای پس از کسره = دوگانه‌واکه"),
    ("بَیان",          "bayân",      "یای پس از فتحه = دوگانه‌واکه"),
    ("خانه",           "khâne",      "های پایانی پس از همخوان = مصوتِ e"),
    ("راه",            "râh",        "های پایانی پس از مصوت = همخوان"),
    ("بَررَسیِ",         "barrasi-ye", "کسرهٔ پایانِ واژه = اضافه، پس از مصوت"),
    ("پِیوَندِ",         "peyvand-e",  "همان اضافه، ولی پس از همخوان"),
    ("تَجرُبهٔ",         "tajrobe-ye", "های همزه‌دار = e + اضافه"),
    ("پایه‌ای",         "pâyei",      "نیم‌فاصله + «ای» = تکواژِ نکره"),
    ("اِدراک",          "edrâk",      "الفِ آغازین تکیه‌گاهِ مصوتِ کوتاه است"),
    ("باوَر",           "bâvar",      "الفِ میانی = مصوتِ بلند"),
    ("آب",             "âb",         "آ همیشه بلند"),
    ("حِس",            "hes",        ""),
    ("و",              "va",         "واو به‌تنهایی = حرفِ ربط"),
    ("اَهَمیَت",         "ahamyat",    "یای پیش از اعراب = همخوان"),
]


def main():
    bad = 0
    for fa, want, why in CASES:
        got = F.convert(fa, "finglish")
        ok = got == want
        if not ok:
            bad += 1
        print("%s %-14s → %-12s %s%s" %
              ("✓" if ok else "✗", fa, got,
               "" if ok else "(انتظار: %s) " % want,
               why))
    # هر سه الفبا باید همان واژه‌ها را بی هیچ نویسهٔ گم‌شده بدهند
    for m in ("finglish", "respell", "ipa"):
        for fa, _, _ in CASES:
            out = F.convert(fa, m)
            if not out.strip():
                print("✗ %s در حالتِ %s خالی برگشت" % (fa, m)); bad += 1
    # و هیچ نویسهٔ فارسی نباید در خروجی بماند — ماندنش یعنی مدلی که فارسی
    # نمی‌داند همان‌جا فاصله می‌گذارد و واژه می‌پاشد.
    for m in ("finglish", "respell", "ipa"):
        out = F.convert(" ".join(c[0] for c in CASES), m)
        left = sorted(set(c for c in out if "؀" <= c <= "ۿ"))
        if left:
            print("✗ نویسهٔ فارسی در خروجیِ %s ماند: %s" % (m, left)); bad += 1
    # ══ سنجه‌ای که می‌گوید این ابزار کِی به درد نمی‌خورَد ══
    # همهٔ کار روی اعراب سوار است. متنِ بی‌اعراب خوشهٔ همخوان می‌سازد
    # («بررسی» → brrsi) که هیچ مدلی نمی‌تواند بخوانَد. اگر این سنجه روزی
    # خاموش شود، ما یک ابزارِ بی‌اثر را سالم گزارش می‌کنیم.
    good = "دَر بَررَسیِ مَعرِفَت‌شِناسیِ اِدراک، حِس و باوَر بَرخوردار اَست."
    plain = "در بررسی معرفت‌شناسی ادراک، حس و باور برخوردار است."
    cg, cp = F.coverage(good), F.coverage(plain)
    if cg["vowelless_count"]:
        print("✗ متنِ اعراب‌دار خوشهٔ همخوان داد: %s" % cg["vowelless_words"]); bad += 1
    else:
        print("✓ متنِ اعراب‌دار: هیچ خوشهٔ همخوانی نیست")
    if cp["vowelless_count"] < 2:
        print("✗ متنِ بی‌اعراب باید هشدار بدهد و نداد"); bad += 1
    else:
        print("✓ متنِ بی‌اعراب هشدار می‌دهد: %s" % cp["vowelless_words"][:4])

    # ══ جوابِ درست، از دستِ اولِ خودِ مدل ══
    # `KiaBush/Persian-IPA-to-Speech-F5` در `examples/metadata.json` برای
    # هر نمونهٔ صوتی‌اش IPAی دقیق را نوشته. تا اجرای #۱۶ ما قراردادِ IPA را
    # **حدس** زده بودیم و گزارش گفت «۱۰۰٪ ناشناخته» — که هم غلط بود (ایرادِ
    # خوانندهٔ ما) و هم پنهان‌کنندهٔ هفت اختلافِ واقعیِ قرارداد.
    print("۴ — همخوانی با قراردادِ اعلام‌شدهٔ مدل")
    PAIRS = [
        ("مِرسی آقایِ رونالدو، بابَتِ این هَمِه سالی کِه اَز بودَنَت لَذَّت "
         "بُردیم، وَ بِالاَخَرِه، اَشکهاش، جاری خواهَند شُد.",
         "meɾsiː ʔɒːɡhɒːje, ɾonɒːldo, bɒːbæte ʔiːn hæme sɒːliː ke ʔæz "
         "buːdænet lezzæt boɾdiːm, væ belæxæɾeh, ʔæʃkhɒːʃ, dʒɒːɾiː xɒːhænd ʃod."),
        ("آن روز جَعفَر تا لَبِ اَروَند آمَد و، تَمامِ اِلتِماس‌ها وَ "
         "اَشکهایَش، بَرایِ حُضورِ او دَر عَمَلیّات، کارساز نَبود.",
         "ʔɒːn ɾuːz dʒæʔfæɾ tɒː læbe ʔæɾvænd ʔɒːmædo,tæmɒːme ʔeltemɒːshɒː væ "
         "ʔæʃkhɒːjæʃ, bæɾɒːje hozuːɾe ʔuː dæɾ ʔæmæliːjɒːt, kɒːɾsɒːz næbuːd."),
    ]
    for fa, ref in PAIRS:
        got = F.convert(fa, "ipa")
        extra = sorted(set(got) - set(ref))
        if extra:
            print("✗ نویسه‌ای می‌سازیم که در قراردادِ مدل نیست: %s" % extra)
            print("   %s" % got); bad += 1
        else:
            print("  ✓ هیچ نویسه‌ای بیرون از قراردادِ مدل ساخته نمی‌شود")
        # و همپوشانیِ واژه‌ها، چون «الفبا درست» با «تلفظ درست» یکی نیست
        A = set(ref.replace(",", " ").split())
        B = set(got.replace(",", " ").split())
        share = len(A & B) * 100 // max(1, len(A))
        # ══ چرا آستانه ۵۵٪ و نه بالاتر ══
        # فایلِ خودشان جوابِ کاملاً دقیقی نیست: «آقای» را `ʔɒːɡhɒːje` نوشته
        # (یعنی ق را `ɡh`، که آوانگاری نیست)، «بالاخره» را `belæxæɾeh`، و
        # نامِ خارجیِ «رونالدو» را به سلیقهٔ خودش. این‌ها اختلافِ قرارداد
        # نیستند، سهل‌انگاریِ نویسندهٔ همان فایل‌اند. سنجهٔ قطعی، مجموعهٔ
        # **نویسه‌ها**ست — چون همان است که تعیین می‌کند مدل نشانه را
        # می‌شناسد یا به فاصله بدلش می‌کند.
        if share < 55:
            print("✗ همپوشانیِ واژه‌ها فقط %d٪ است" % share); bad += 1
        else:
            print("  ✓ همپوشانیِ واژه‌ها با نمونهٔ خودشان: %d٪" % share)

    # و کمانِ پیوند، که تنها نویسهٔ ناشناختهٔ اجرای #۱۶ بود
    if "\u0361" in F.convert("جوجه چای", "ipa"):
        print("✗ کمانِ پیوند (U+0361) برگشته — همان یک نویسه‌ای که مدل نداشت")
        bad += 1
    else:
        print("  ✓ کمانِ پیوند ساخته نمی‌شود (dʒ نه d͡ʒ)")

    print("\n%s" % ("همه گذشت." if not bad else "%d مورد نگذشت." % bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
